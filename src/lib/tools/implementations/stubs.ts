import type { Tool, ToolName } from "../types";

/** Generates a stub tool that is fully documented (satisfies the "explain
 *  every tool" requirement) but honestly reports it isn't implemented yet,
 *  rather than faking a capability that doesn't exist (e.g. real code
 *  execution or diagram rendering). */
function stubTool(meta: Omit<Tool["metadata"], "implemented">): Tool {
  return {
    metadata: { ...meta, implemented: false },
    async run() {
      return {
        tool: meta.name,
        success: false,
        error: `${meta.name} is registered but not yet implemented.`,
      };
    },
  };
}

