import { access, mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const serverDir = join(root, "dist", "server");
const shimPath = join(serverDir, "server.js");
const candidates = [
  join(serverDir, "_ssr", "ssr.mjs"),
  join(serverDir, "index.mjs"),
];

await mkdir(serverDir, { recursive: true });
const entryPath = await (async () => {
  for (const candidate of candidates) {
    try {
      await access(candidate);
      return candidate;
    } catch {
      // Try the next candidate.
    }
  }

  throw new Error("[fix-server-preview] No compatible server entry was generated by the build.");
})();

const relativeEntry = entryPath.startsWith(serverDir)
  ? `.${entryPath.slice(serverDir.length).replace(/\\/g, "/")}`
  : entryPath;

await writeFile(
  shimPath,
  `import server from ${JSON.stringify(relativeEntry)};\nexport default server;\n`,
  "utf8",
);

console.log(`[fix-server-preview] Created dist/server/server.js compatibility shim for ${relativeEntry}.`);
